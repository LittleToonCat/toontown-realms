from direct.directnotify.DirectNotifyGlobal import directNotify

from toontown.parties.ActivityBase import ActivityBase
from toontown.parties import PartyGlobals
from toontown.parties.DistributedPartyJukeboxActivityBaseAI import DistributedPartyJukeboxActivityBaseAI
from toontown.toonbase import ToontownGlobals


class DistributedSafezoneJukeboxAI(DistributedPartyJukeboxActivityBaseAI):
    notify = directNotify.newCategory('DistributedSafezoneJukeboxAI')

    def __init__(self, air, x, y, z, h, parent):
        # The value of parent is the zoneId in this context so we can have the jukebox
        # respond to fireworks but that's all it's used for here
        self.activity = ActivityBase(PartyGlobals.ActivityIds.PartyJukebox, x, y, h)
        DistributedPartyJukeboxActivityBaseAI.__init__(self, air, parent, self.activity)
        # Override the values generated by the grid calculation
        self.x = self.activity.x
        self.y = self.activity.y
        self.h = self.activity.h
        self.z = z
        self.music = PartyGlobals.PhaseToMusicDataSz

    def delete(self):
        del self.activity
        DistributedPartyJukeboxActivityBaseAI.delete(self)

    def setZ(self, z):
        self.z = z

    def d_setZ(self, z):
        self.sendUpdate('setZ', [z])

    def b_setZ(self, z):
        self.setZ(z)
        self.d_setZ(z)

    def getZ(self):
        return self.z

    def requestLoop(self):
        avId = self.air.getAvatarIdFromSender()
        if not avId:
            return

        av = self.air.doId2do.get(avId)
        if not av:
            return

        if avId != self.currentToon:
            self.air.writeServerEvent('suspicious', avId=avId, issue='Toon tried to loop song without using the jukebox!')
            return

        if av.getAccessLevel() < 200:
            self.air.writeServerEvent('suspicious', avId=avId, issue='Toon tried to loop song to the top but has insufficient access!')
            return

        self.loop = not self.loop

        self.d_setLoop(self.loop)

    def moveHostSongToTopRequest(self):
        avId = self.air.getAvatarIdFromSender()
        if not avId:
            return

        av = self.air.doId2do.get(avId)
        if not av:
            return

        if avId != self.currentToon:
            self.air.writeServerEvent('suspicious', avId=avId,
                                      issue='Toon tried to set song without using the jukebox!')
            return

        if av.getAccessLevel() < 200:
            self.air.writeServerEvent('suspicious', avId=avId, issue='Toon tried to move song to the top but has insufficient access!')
            return

        if avId not in self.owners:
            self.air.writeServerEvent('suspicious', avId=avId,
                                      issue='Toon tried to move non-existent song to the top of the queue!')
            return

        index = self.owners.index(avId)
        self.owners.remove(avId)
        song = self.queue.pop(index)
        self.owners.insert(0, avId)
        self.queue.insert(0, song)
        for avId in self.toonsPlaying:
            self.sendUpdateToAvatarId(avId, 'moveHostSongToTop', [])

    def getRandomMusicInfo(self, phase=-1):
        if self.zoneId == ToontownGlobals.ToontownOutskirts:
            defaultSong = [14.5, 'SP_nbrhood_{}.ogg'.format(self.air.outskirtsTheme)]
        elif self.zoneId == ToontownGlobals.ToontownCentral:
            if self.air.holidayManager.isHolidayRunning(ToontownGlobals.HALLOWEEN_PROPS) or self.air.holidayManager.isHolidayRunning(ToontownGlobals.SPOOKY_PROPS):
                defaultSong = [4, 'ttoff_s_ara_ttc_nbrhood_halloween.ogg']
            elif self.air.holidayManager.isHolidayRunning(ToontownGlobals.WINTER_DECORATIONS) or self.air.holidayManager.isHolidayRunning(ToontownGlobals.WACKY_WINTER_DECORATIONS):
                defaultSong = [4, 'ttoff_s_ara_ttc_nbrhood_winter.ogg']
            else:
                defaultSong = [4, 'TC_nbrhood.ogg']
        else:
            defaultSong = DistributedPartyJukeboxActivityBaseAI.getRandomMusicInfo(self, phase)
        return defaultSong
